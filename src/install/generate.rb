# frozen_string_literal: true

require "erb"
require "fileutils"
require_relative "utils"

module Installer
  # Writes the generated configs into home/, where stow links them into $HOME.
  module Generate
    SHELL_DIR = File.expand_path("../..", __dir__)
    TEMPLATES = File.join(SHELL_DIR, "src", "templates")
    HEADER = "# THIS FILE IS AUTO-GENERATED. DO NOT EDIT THIS FILE DIRECTLY.\n\n"
    ZSH_PARTS = %w[base zsh-config aliases git functions kubernetes agents misc].freeze
    ZSHRC = File.join(SHELL_DIR, "home", ".zshrc")
    GITCONFIG = File.join(SHELL_DIR, "home", ".gitconfig")
    GHOSTTY_CONFIG = File.join(SHELL_DIR, "home", ".config", "ghostty", "config-os")

    module_function

    def run!(targets)
      targets.each { |target| send("write_#{target}!") }
    end

    def zshrc
      parts = ZSH_PARTS.to_h do |part|
        [:"#{part.tr("-", "_")}_template_contents", render(File.join(TEMPLATES, "#{part}.sh.erb"))]
      end
      HEADER + ERB.new(read(File.join(TEMPLATES, ".zshrc.erb")), trim_mode: "-").result_with_hash(parts)
    end

    def write_zsh!
      File.write(ZSHRC, zshrc)
      Installer::Utils.log("Generated #{ZSHRC}")
      generate_completions
    end

    # The template reads GIT_NAME, GIT_EMAIL and GIT_SIGNING_KEY from the environment.
    def gitconfig
      HEADER + render(File.join(TEMPLATES, ".gitconfig.erb"))
    end

    def write_git!
      File.write(GITCONFIG, gitconfig)
      Installer::Utils.log("Generated #{GITCONFIG}")
    end

    # Ghostty renders fonts smaller on macOS (CoreText) than on Linux (FreeType) at the same size.
    def ghostty_config(ruby_platform: RUBY_PLATFORM)
      font_size = ruby_platform.include?("darwin") ? 13 : 11
      "# Generated by task generate:ghostty\nfont-size = #{font_size}\n"
    end

    def write_ghostty!
      FileUtils.mkdir_p(File.dirname(GHOSTTY_CONFIG))
      File.write(GHOSTTY_CONFIG, ghostty_config)
      Installer::Utils.log("Generated #{GHOSTTY_CONFIG}")
    end

    def render(path)
      ERB.new(read(path), trim_mode: "-").result
    end

    # The templates hold UTF-8 (em dashes), whatever the locale says.
    def read(path)
      File.read(path, encoding: Encoding::UTF_8)
    end

    def generate_completions
      shell_dir = SHELL_DIR
      completions_dir = File.join(shell_dir, 'home', '.config', 'zsh', 'completions')
      todo_bin = File.join(shell_dir, 'home', 'bin', 'todo')

      FileUtils.mkdir_p(completions_dir)

      if File.executable?(todo_bin)
        output = `#{todo_bin} --completions zsh 2>/dev/null`
        if $?.success? && !output.empty? # rubocop:disable Style/SpecialGlobalVars
          File.write(File.join(completions_dir, '_todo'), output)
          Installer::Utils.log("Generated zsh completions at #{completions_dir}/_todo")
        else
          Installer::Utils.warn('Failed to generate todo completions')
        end
      else
        Installer::Utils.warn("todo binary not found at #{todo_bin}, skipping completions")
      end

      # task or go-task provides the same completions, so we check for either one.
      # GO_TASK_EXE tells the completion script which command name to bind to.
      # If the binary is named 'task' we set GO_TASK_EXE=task so the generated
      # completion registers as `compdef _go_task task`, not `compdef _go_task go-task`.
      task_bin = `command -v task 2>/dev/null`.strip
      task_exe_name = task_bin.empty? ? 'go-task' : File.basename(task_bin)
      if task_bin.empty?
        task_bin = `command -v go-task 2>/dev/null`.strip
      end

      if !task_bin.empty? && File.executable?(task_bin)
        output = `#{task_bin} --completion zsh 2>/dev/null`
        if $?.success? && !output.empty? # rubocop:disable Style/SpecialGlobalVars
          # The completion script defaults to 'go-task' as the bound command name.
          # Two patches are required so `task<TAB>` works without completing `go_task` first:
          #
          # 1. Patch the runtime default so GO_TASK_CMD resolves to the actual binary.
          output = output.gsub('${GO_TASK_EXE:-go-task}', "${GO_TASK_EXE:-#{task_exe_name}}")
          #
          # 2. Patch the #compdef autoload header to include all command variants
          #    (go_task, task, go-task) so compinit registers completions for each.
          output = output.sub(/^(#compdef\s+go_task.*)$/, "\\1 task go-task")

          # 3. Add a _task() wrapper so the file works when autoloaded as _task.
          #    go-task generates _go_task() but compinit names the function after
          #    the file (_task). The wrapper delegates to the real implementation.
          output += "\n_task() { _go_task \"$@\" }\n"

          task_comp_file = File.join(completions_dir, '_task')
          File.write(task_comp_file, output)
          Installer::Utils.log("Generated zsh completions at #{task_comp_file}")

          # Clean up stale symlinks from previous versions of this script.
          ['_go-task', '_go_task'].each do |name|
            stale = File.join(completions_dir, name)
            FileUtils.rm_f(stale) if File.symlink?(stale)
          end

          # Invalidate the zcompdump cache so compinit picks up the new
          # #compdef mappings on the next shell start.
          zcompdump = File.join(Dir.home, '.zcompdump')
          FileUtils.rm_f(zcompdump) if File.exist?(zcompdump)
        else
          Installer::Utils.warn('Failed to generate task completions')
        end
      else
        Installer::Utils.warn('task binary not found, skipping task completions')
      end
    end
  end
end
